/**
 * Return an inline SVG string for the named icon.
 * Decorative by default (aria-hidden). Size follows the surrounding font size.
 */
function icon(name, options = {}) {
    const body = PATHS[name];
    if (!body) {
        console.warn(`Unknown icon: ${name}`);
        return '';
    }
    const cls = options.class ? `icon-svg ${options.class}` : 'icon-svg';
    return `<svg class="${cls}" width="1em" height="1em" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${body}</svg>`;
}

